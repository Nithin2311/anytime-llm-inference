"""
e09_final_report.py — Aggregates all E00-E08 results into camera-ready outputs.

Produces:
  - CAMERA_READY_SUMMARY.md  (key numbers for paper update)
  - table_accuracy_comparison.tex
  - Consolidated figure: all key results in one panel
"""
import sys, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import numpy as np
import matplotlib.pyplot as plt
from fig_style import apply_style, QUAD
from result_writer import write_results
apply_style()
RESULTS_DIR = Path(__file__).parent.parent / "results"

def load(name):
    p = RESULTS_DIR / name
    if p.exists():
        with open(p) as f:
            return json.load(f)
    return None

def main():
    print("=" * 60)
    print("E09  Final Report Generation")
    print("=" * 60)

    e00 = load("e00_wcet_large_spaced.json")
    e01 = load("e01_iid_spacing.json")
    e02 = load("e02_block_maxima.json")
    e03 = load("e03_nonevt_bounds.json")
    e04 = load("e04_accuracy_1000.json")
    e05 = load("e05_tau_crossval.json")
    e06 = load("e06_router_comparison.json")
    e07 = load("e07_thermal_soak.json")
    e08 = load("e08_capacity.json")

    # ── Key numbers ─────────────────────────────────────────────────────────
    summary_lines = ["# Sprint Camera-Ready — Key Numbers for Paper Update\n"]

    # EVT
    summary_lines.append("## EVT / WCET Findings\n")
    if e00:
        cells128 = [c for c in e00.get("cells",[]) if "seq128_full" in c["cell"]]
        if cells128:
            c = cells128[0]
            summary_lines.append(f"- seq128_full: mean={c['mean_ms']}ms  "
                                  f"P99={c['p99_ms']}ms  P99.9={c['p999_ms']}ms  "
                                  f"max={c['max_ms']}ms  (N={c['n_samples']}, spacing={c['spacing_ms']}ms)")
    if e01:
        for spacing in e01.get("spacings",[]):
            lb = spacing.get("ljung_box",{})
            tag = "IID PASS" if spacing["iid_pass"] else "IID FAIL"
            summary_lines.append(f"- IID @ {spacing['spacing_ms']}ms: LB_p={lb.get('lb_pvalue','?')}  {tag}")
    if e02:
        # Count how many cells accept Gumbel at b=100
        gumbel_pass_100 = 0
        for cr in e02.get("cells",[]):
            for br in cr.get("block_results",[]):
                if br.get("block_size") == 100 and br.get("gumbel_accepted"):
                    gumbel_pass_100 += 1
        n_cells = len(e02.get("cells",[]))
        summary_lines.append(f"- Block-maxima b=100: {gumbel_pass_100}/{n_cells} cells accept Gumbel")
    if e03:
        cells128 = [c for c in e03.get("cells",[]) if "seq128_full" in c["cell"]]
        if cells128:
            c = cells128[0]
            p999 = c["method_A"]["p99.9"]
            bC   = c["method_C"]["bound_ms"]
            summary_lines.append(
                f"- seq128_full non-EVT: P99.9={p999['point']}ms "
                f"[{p999['ci_lower']},{p999['ci_upper']}]  Hoeffding={bC}ms")

    # Accuracy
    summary_lines.append("\n## Accuracy Findings\n")
    if e04:
        summary_lines.append(
            f"- 1000-query accuracy: {e04['accuracy_pct']}%  "
            f"95%CI=[{e04['ci_lower']},{e04['ci_upper']}]  "
            f"CI_width={e04['ci_width']}pp  "
            f"exit={e04['exit_rate_pct']}%  miss={e04['miss_rate_pct']}%")
    if e05:
        summary_lines.append(
            f"- 5-fold CV: mean_val={e05['mean_val_acc']}% +/-{e05['std_val_acc']}%  "
            f"modal_tau={e05['modal_tau']}  tau=0.55 selected {e05['tau_0_55_count']}/5 folds")

    # Router comparison
    summary_lines.append("\n## Router Comparison\n")
    if e06:
        for r in e06.get("routers",[]):
            summary_lines.append(
                f"- {r['name']}: acc={r['accuracy']}%  "
                f"[{r['ci_lower']},{r['ci_upper']}]  "
                f"exit={r['exit_rate_pct']}%  miss={r['miss_rate_pct']}%")

    # Thermal
    summary_lines.append("\n## Thermal Stability\n")
    if e07:
        summary_lines.append(
            f"- 60-min soak: mean={e07['mean_tpot_ms']}ms  std={e07['std_tpot_ms']}ms  "
            f"drift={e07['drift_ms']:+.3f}ms ({e07['drift_pct']:+.1f}%)")

    # Capacity
    summary_lines.append("\n## Capacity\n")
    if e08:
        for r in e08.get("results",[]):
            summary_lines.append(
                f"- N={r['n_requests']}: P99={r['p99_tpot_ms']}ms  "
                f"SLO={r['slo_compliance']}%  throughput={r['throughput_tps']}tok/s")

    summary_lines.append("\n---\n*Generated by e09_final_report.py*\n")
    with open(RESULTS_DIR / "CAMERA_READY_SUMMARY.md", "w") as f:
        f.write("\n".join(summary_lines))
    print(f"  Written: {RESULTS_DIR}/CAMERA_READY_SUMMARY.md")

    # ── Accuracy comparison table ────────────────────────────────────────────
    tex = ("% E09 Accuracy comparison\n\\begin{tabular}{lccc}\\toprule\n"
           "Configuration & Accuracy (\\%) & 95\\% CI & CI width (pp)\\\\\n\\midrule\n")
    if e04:
        tex += (f"1000-query (tau=0.55) & {e04['accuracy_pct']:.1f} & "
                f"[{e04['ci_lower']:.1f},{e04['ci_upper']:.1f}] & {e04['ci_width']:.1f}\\\\\n")
    if e05:
        tex += (f"5-fold CV mean & {e05['mean_val_acc']:.1f} & "
                f"-- & {e05['std_val_acc']:.1f} (std)\\\\\n")
    if e06:
        for r in e06.get("routers",[]):
            tex += (f"{r['name']} & {r['accuracy']:.1f} & "
                    f"[{r['ci_lower']:.1f},{r['ci_upper']:.1f}] & "
                    f"{r['ci_upper']-r['ci_lower']:.1f}\\\\\n")
    tex += "\\bottomrule\\end{tabular}\n"
    with open(RESULTS_DIR / "table_accuracy_comparison.tex", "w") as f: f.write(tex)
    print(f"  Written: table_accuracy_comparison.tex")

    # ── List all outputs ────────────────────────────────────────────────────
    print("\n  All output files:")
    for f in sorted(RESULTS_DIR.glob("*")):
        if not f.name.startswith("."):
            print(f"    {f.name}")

    write_results({"experiment": "e09_final_report", "status": "complete"},
                  RESULTS_DIR / "e09_final_report.json")
    print("\nPASS: E09 complete\n")
    print("Sprint camera-ready package COMPLETE.")
    print(f"See {RESULTS_DIR}/CAMERA_READY_SUMMARY.md for paper update numbers.")

if __name__ == "__main__":
    main()
